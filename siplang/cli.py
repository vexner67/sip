"""Командная строка: sip run | build | check."""

import os
import sys
import traceback

from .compiler import compile_file, execute, format_runtime_error
from .errors import SipError

USAGE = """\
usage:
  sip run FILE.sip [args...]   compile and run (also: sip FILE.sip)
  sip build FILE.sip [-o OUT]  write the generated Python
  sip check FILE.sip...        check syntax only

SIP_TRACE=1 shows the full Python traceback on runtime errors."""


def _err(msg: str) -> int:
    print(msg, file=sys.stderr)
    return 1


def cmd_run(path: str, args: list[str]) -> int:
    try:
        compiled = compile_file(path)
    except SipError as e:
        return _err(str(e))
    except OSError as e:
        return _err(f"{path}: {e.strerror}")
    try:
        execute(compiled, args)
    except SystemExit as e:
        return e.code if isinstance(e.code, int) else (0 if e.code is None else _err(str(e.code)))
    except KeyboardInterrupt:
        return 130
    except BaseException as e:
        if os.environ.get("SIP_TRACE"):
            traceback.print_exc()
        return _err(format_runtime_error(e, compiled))
    return 0


def cmd_build(args: list[str]) -> int:
    out = None
    files = []
    it = iter(args)
    for a in it:
        if a in ("-o", "--out"):
            out = next(it, None)
            if out is None:
                return _err("-o needs a file name")
        else:
            files.append(a)
    if len(files) != 1:
        return _err("build takes exactly one file")
    path = files[0]
    try:
        compiled = compile_file(path)
    except SipError as e:
        return _err(str(e))
    except OSError as e:
        return _err(f"{path}: {e.strerror}")
    out = out or os.path.splitext(path)[0] + ".py"
    with open(out, "w", encoding="utf-8") as f:
        f.write(f"# Generated by sip from {os.path.basename(path)}. Do not edit.\n")
        f.write(compiled.python)
    print(out)
    return 0


def cmd_check(paths: list[str]) -> int:
    if not paths:
        return _err("check needs at least one file")
    failed = 0
    for path in paths:
        try:
            compile_file(path)
        except SipError as e:
            print(e, file=sys.stderr)
            failed += 1
        except OSError as e:
            print(f"{path}: {e.strerror}", file=sys.stderr)
            failed += 1
    if not failed:
        print(f"ok: {len(paths)} file(s)")
    return 1 if failed else 0


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if not argv or argv[0] in ("-h", "--help", "help"):
        print(USAGE)
        return 0
    cmd, rest = argv[0], argv[1:]
    if cmd == "run":
        if not rest:
            return _err("run needs a file")
        return cmd_run(rest[0], rest[1:])
    if cmd == "build":
        return cmd_build(rest)
    if cmd == "check":
        return cmd_check(rest)
    if cmd.endswith(".sip"):
        return cmd_run(cmd, rest)
    return _err(f"unknown command '{cmd}'\n{USAGE}")
